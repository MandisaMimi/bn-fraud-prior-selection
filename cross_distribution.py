"""
cross_distribution.py
======================
Addresses the supervisor feedback directly: the main experiment (main.py)
only ever computes KL(P_true || P_learned), where P_learned is a structure
LEARNED FROM DATA GENERATED BY P_true itself. Even though Hill Climbing
doesn't recover P_true perfectly (see the non-trivial SHD/precision/recall
values already in outputs/main_experiment_results.csv), P_learned is still
always an ESTIMATE OF THE SAME underlying distribution -- there is no
result in the existing pipeline showing what KL divergence looks like
between two GENUINELY DIFFERENT distributions.

This module adds that missing comparison. For a set of seed pairs (i, j)
with i != j:

  1. Build TWO independent ground-truth networks, P (seed i) and R (seed j)
     -- different random DAG structure AND different CPTs, via the exact
     same ground_truth.build_ground_truth() used everywhere else.
  2. Generate a dataset from EACH.
  3. Learn Q by running Hill Climbing on R's data (NOT P's data) -- this is
     the "Q learned from a different distribution" the supervisor asked for.
     For comparison, ALSO learn P_hat by running Hill Climbing on P's own
     data, exactly as main.py already does.
  4. Using the SAME held-out-log-likelihood estimator as evaluation.py,
     compute both:
       KL(P_true || P_hat)  -- same-distribution case (already in main.py)
       KL(P_true || Q)      -- different-distribution case (NEW)
  5. Report both side by side. If the evaluation methodology is sound,
     KL(P_true || Q) should be substantially and consistently LARGER than
     KL(P_true || P_hat) across every seed pair -- demonstrating that the
     metric genuinely discriminates between "recovered the right
     distribution (imperfectly)" and "learned an unrelated distribution
     entirely", rather than being trivially near-zero regardless of input.
"""

import time
import random
import numpy as np
import pandas as pd

import config
import ground_truth
import data_generation
import structure_learning
import evaluation


def run_single_pair(seed_p: int, seed_q: int, rows=None, verbose=True):
    """
    Executes one (P, Q) comparison:
      - P: ground truth for seed_p, learned back from its OWN data (P_hat)
      - Q: a structure learned from seed_q's data entirely, evaluated
           against seed_p's ground truth (a genuine distribution mismatch)
    """
    rows = rows or config.ROWS_PER_DATASET
    t0 = time.time()

    random.seed(seed_p)
    np.random.seed(seed_p)

    # --- Ground truth P (the reference distribution for this pair) --------
    gt_p = ground_truth.build_ground_truth(seed_p)
    true_edges_p = [(par, n) for n, plist in gt_p["parents"].items() for par in plist]

    data_rng_p = np.random.RandomState(seed_p + 10_000)
    train_p = data_generation.generate_dataset(gt_p, rows, data_rng_p)
    holdout_p = data_generation.generate_dataset(gt_p, config.HOLDOUT_ROWS, data_rng_p)

    # --- Ground truth R (an entirely independent distribution) ------------
    random.seed(seed_q)
    np.random.seed(seed_q)
    gt_r = ground_truth.build_ground_truth(seed_q)

    data_rng_r = np.random.RandomState(seed_q + 10_000)
    train_r = data_generation.generate_dataset(gt_r, rows, data_rng_r)

    # --- Same-distribution case: learn P_hat from P's own data -----------
    learned_edges_phat = structure_learning.learn_structure(train_p)
    model_phat = structure_learning.fit_learned_model(train_p, learned_edges_phat, config.NODES)
    parents_phat, marg_phat, cpts_phat = evaluation.pgmpy_model_to_dict(model_phat)

    kl_same_mean, kl_same_std = evaluation.estimate_kl_divergence(
        holdout_p,
        gt_p["parents"], gt_p["marginals"], gt_p["cpts"],
        parents_phat, marg_phat, cpts_phat,
    )

    # --- Different-distribution case: learn Q from R's data, but score ---
    # --- it against P's held-out data (the genuine mismatch case) --------
    learned_edges_q = structure_learning.learn_structure(train_r)
    model_q = structure_learning.fit_learned_model(train_r, learned_edges_q, config.NODES)
    parents_q, marg_q, cpts_q = evaluation.pgmpy_model_to_dict(model_q)

    kl_diff_mean, kl_diff_std = evaluation.estimate_kl_divergence(
        holdout_p,
        gt_p["parents"], gt_p["marginals"], gt_p["cpts"],
        parents_q, marg_q, cpts_q,
    )

    elapsed = time.time() - t0
    if verbose:
        print(f"  P=seed{seed_p:>3d}  Q=seed{seed_q:>3d}  "
              f"KL(P||P_hat)={kl_same_mean:6.3f}   KL(P||Q)={kl_diff_mean:6.3f}   "
              f"ratio={kl_diff_mean/max(kl_same_mean, 1e-6):5.1f}x   ({elapsed:.1f}s)")

    return {
        "seed_p": seed_p,
        "seed_q": seed_q,
        "kl_same_distribution": kl_same_mean,
        "kl_same_distribution_std": kl_same_std,
        "kl_different_distribution": kl_diff_mean,
        "kl_different_distribution_std": kl_diff_std,
        "ratio": kl_diff_mean / max(kl_same_mean, 1e-6),
        "elapsed_seconds": elapsed,
    }


def run_cross_distribution_experiment(n_pairs=10, base_seed=200, rows=None, verbose=True):
    """
    Runs n_pairs independent (P, Q) comparisons using non-overlapping seeds,
    and returns a DataFrame of results plus summary statistics.
    """
    results = []
    for i in range(n_pairs):
        seed_p = base_seed + 2 * i
        seed_q = base_seed + 2 * i + 1
        results.append(run_single_pair(seed_p, seed_q, rows=rows, verbose=verbose))

    df = pd.DataFrame(results)
    return df


if __name__ == "__main__":
    print(f"Running cross-distribution experiment: comparing KL(P||P_hat) "
          f"[same distribution] against KL(P||Q) [different distribution]")
    print("-" * 100)
    df = run_cross_distribution_experiment(n_pairs=10)

    print("\nSummary (mean +/- std across all pairs):")
    print(f"  KL(P||P_hat) [same distribution]:      "
          f"{df['kl_same_distribution'].mean():.3f} +/- {df['kl_same_distribution'].std():.3f}")
    print(f"  KL(P||Q)     [different distribution]: "
          f"{df['kl_different_distribution'].mean():.3f} +/- {df['kl_different_distribution'].std():.3f}")
    print(f"  Mean ratio (different / same): {df['ratio'].mean():.1f}x")

    df.to_csv("outputs/cross_distribution_results.csv", index=False)
    print("\nSaved -> outputs/cross_distribution_results.csv")
